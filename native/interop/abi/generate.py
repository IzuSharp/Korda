#!/usr/bin/env python3
"""Generate the shared fixed ABI and probes from its single versioned description."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SCHEMA = Path(__file__).with_name("abi-v1.json")
C = {"u32": "uint32_t", "i32": "int32_t", "u64": "uint64_t", "uintptr": "uintptr_t",
     "bytes_ptr": "const uint8_t *", "void_ptr": "const void *", "error_ptr": "const nw_error_info_v1 *",
     "abi_ptr": "nw_abi_info_v1 *", "terminal_fn": "nw_on_terminal_fn", "event_fn": "nw_on_event_fn"}
CS = {"u32": "uint", "i32": "int", "u64": "ulong", "uintptr": "nuint", "bytes_ptr": "byte*",
      "void_ptr": "void*", "error_ptr": "NwErrorInfoV1*", "abi_ptr": "NwAbiInfoV1*"}


def pascal(value):
    return "".join(part.capitalize() for part in value.split("_"))


def generated(schema):
    digest = hashlib.sha256(SCHEMA.read_bytes()).hexdigest()
    tag = f"Generated from abi-v1.json; SHA-256 {digest}. Do not edit."
    callbacks = {callback["name"]: callback for callback in schema["callbacks"]}
    cs_types = dict(CS)
    for kind in ("terminal_fn", "event_fn"):
        callback = callbacks[C[kind]]
        signature = [CS[kind] for _, kind in callback["parameters"]] + [CS[callback["return"]]]
        cs_types[kind] = "delegate* unmanaged[Cdecl]<" + ", ".join(signature) + ">"
    h = [f"/* {tag} */", "#ifndef KORDA_ABI_V1_H", "#define KORDA_ABI_V1_H",
         "#include <stdint.h>", "#include <stddef.h>", "#if defined(_WIN32)", "#define NW_CDECL __cdecl",
         "#else", "#define NW_CDECL", "#endif", "#ifdef __cplusplus", 'extern "C" {', "#endif",
         "typedef uint32_t nw_status;"]
    cs = [f"// <auto-generated>{tag}</auto-generated>", "using System.Runtime.InteropServices;",
          "namespace Korda.Interop.Abi;", "internal static class NativeStatus", "{"]
    for name, value in schema["statuses"].items():
        h.append(f"#define NW_{name} UINT32_C({value})")
        cs.append(f"    internal const uint {pascal(name)} = {value};")
    cs.append("}")
    # Forward declarations allow callbacks to borrow a typed error record.
    for rec in schema["records"]:
        h.append(f"typedef struct {rec['name']} {rec['name']};")
    for cb in schema["callbacks"]:
        parameters = ", ".join(f"{C[t]} {n}" for n, t in cb["parameters"])
        c_return = "nw_status" if cb["return"] == "u32" else C[cb["return"]]
        h.append(f"typedef {c_return} (NW_CDECL *{cb['name']})({parameters});")
    for rec in schema["records"]:
        name, typ = rec["name"], pascal(rec["name"])
        h.append(f"struct {name} {{")
        cs.extend(["[StructLayout(LayoutKind.Sequential)]", f"internal unsafe struct {typ}", "{"])
        for field, kind in rec["fields"]:
            h.append(f"    {C[kind]} {field};")
            cs.append(f"    internal {cs_types[kind]} {pascal(field)};")
        h.append("};")
        cs.append("}")
    cs.extend(["internal static class WireReservedFields", "{"])
    for rec in schema["records"]:
        if rec.get("zero_fields"):
            checks_cs = " && ".join(f"value.{pascal(field)} == 0" for field in rec["zero_fields"])
            cs.append(f"    internal static bool AreZero(in {pascal(rec['name'])} value) => {checks_cs};")
    cs.append("}")
    bootstrap = schema["bootstrap"]
    bootstrap_parameters = ", ".join(f"{C[kind]} {name}" for name, kind in bootstrap["parameters"])
    bootstrap_return = "nw_status" if bootstrap["return"] == "u32" else C[bootstrap["return"]]
    h.extend([f"typedef {bootstrap_return} (NW_CDECL *nw_get_abi_v1_fn)({bootstrap_parameters});",
              "#ifdef __cplusplus", "}", "#endif", "#endif", ""])
    cs.append("")
    # json.dumps emits a valid quoted C/C++/C# string for this ASCII inventory.
    literal = json.dumps
    cp = [f"/* {tag} */", '#include "korda_abi_v1.h"', "#include <stdio.h>", "#include <stdalign.h>", "int main(void) {",
          '    printf(' + literal('{"pointer_width_bits":%zu,"records":{') + ', sizeof(void*) * 8);']
    mp = [f"// <auto-generated>{tag}</auto-generated>", "using System.Runtime.CompilerServices;", "using System.Runtime.InteropServices;",
          "using System.Text;", "using Korda.Interop.Abi;", "internal static unsafe class LayoutProbe", "{",
          "    internal static string Read()", "    {",
          '        var text = new StringBuilder(' + literal('{"pointer_width_bits":') + ').Append(IntPtr.Size * 8).Append(' + literal(',"records":{') + ');']
    for index, rec in enumerate(schema["records"]):
        name, typ = rec["name"], pascal(rec["name"])
        lead = "," if index else ""
        prefix = lead + '"' + name + '":{"size":'
        cp.append('    printf(' + literal(prefix + '%zu,"align":%zu,"fields":{') + f', sizeof({name}), alignof({name}));')
        mp.append('        text.Append(' + literal(prefix) + f').Append(Unsafe.SizeOf<{typ}>()).Append(' + literal(',"align":') + f').Append(Marshal.OffsetOf<{typ}Alignment>(nameof({typ}Alignment.Value))).Append(' + literal(',"fields":{') + ');')
        for field_index, (field, kind) in enumerate(rec["fields"]):
            fieldlead = "," if field_index else ""
            fieldcs = pascal(field)
            cswidth = CS[kind] if kind in ("u32", "i32", "u64") else "nint"
            prefix = fieldlead + '"' + field + '":{"offset":'
            cp.append('    printf(' + literal(prefix + '%zu,"width":%zu}') + f', offsetof({name}, {field}), sizeof((({name}*)0)->{field}));')
            mp.append('        text.Append(' + literal(prefix) + f').Append(Marshal.OffsetOf<{typ}>(nameof({typ}.{fieldcs}))).Append(' + literal(',"width":') + f').Append(sizeof({cswidth})).Append("}}");')
        cp.append('    printf("}}");')
        mp.append('        text.Append("}}");')
    cp.extend(['    puts("}}");', "    return 0;", "}", ""])
    mp.extend(['        return text.Append("}}").ToString();', "    }", "}"])
    for rec in schema["records"]:
        typ = pascal(rec["name"])
        mp.extend(["[StructLayout(LayoutKind.Sequential)]", f"internal struct {typ}Alignment", "{", "    internal byte Prefix;", f"    internal {typ} Value;", "}"])
    mp.append("")
    # C++ consumes the identical C header. Compile the schema's function types
    # independently so calling convention, argument widths and returns are checked.
    signatures = ['#include <type_traits>']
    for callback in schema["callbacks"]:
        return_type = "nw_status" if callback["return"] == "u32" else C[callback["return"]]
        parameters = ", ".join(C[kind] for _, kind in callback["parameters"])
        signatures.append(f'static_assert(std::is_same_v<{callback["name"]}, {return_type} (NW_CDECL *)({parameters})>);')
    parameters = ", ".join(C[kind] for _, kind in bootstrap["parameters"])
    signatures.append(f'static_assert(std::is_same_v<nw_get_abi_v1_fn, {bootstrap_return} (NW_CDECL *)({parameters})>);')
    cpp = cp[:4] + signatures + cp[4:]
    return {
        "native/interop/abi/include/korda_abi_v1.h": "\n".join(h),
        "src/Interop.Abi/WireRecords.g.cs": "\n".join(cs),
        "tests/Interop.Abi/native/layout.c": "\n".join(cp),
        "tests/Interop.Abi/native/layout.cpp": "\n".join(cpp),
        "tests/Interop.Abi/LayoutProbe.g.cs": "\n".join(mp),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = generated(json.loads(SCHEMA.read_text()))
    stale = []
    for name, contents in outputs.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != contents:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(contents)
    if stale:
        raise SystemExit("Generated ABI drift: " + ", ".join(stale))
    print(json.dumps({"schema_sha256": hashlib.sha256(SCHEMA.read_bytes()).hexdigest(), "generated_files": len(outputs), "check": args.check}))


if __name__ == "__main__":
    main()
