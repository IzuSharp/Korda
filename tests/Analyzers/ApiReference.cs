using System.Reflection;
using System.Xml.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using NativeWeave.Analyzers;

internal static class ApiReference
{
    internal static void Write(string output)
    {
        var assembly = typeof(NativeWeaveAnalyzer).Assembly;
        var exported = assembly.GetExportedTypes();
        if (exported.Length != 1 || exported[0] != typeof(NativeWeaveAnalyzer) || !exported[0].IsSealed || exported[0].BaseType != typeof(DiagnosticAnalyzer))
            throw new InvalidOperationException("The compiler plug-in accidentally exposed another public type or changed its extension seam.");
        var type = exported[0];
        var methods = type.GetMethods(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly).Where(m => !m.IsSpecialName).ToArray();
        var properties = type.GetProperties(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly);
        var constructors = type.GetConstructors();
        if (methods.Length != 1 || methods[0].Name != "Initialize" || methods[0].ReturnType != typeof(void) ||
            methods[0].GetParameters().Single().ParameterType != typeof(AnalysisContext) || constructors.Length != 1 || constructors[0].GetParameters().Length != 0 ||
            properties.Length != 1 || properties[0].Name != "SupportedDiagnostics" || properties[0].CanWrite ||
            properties[0].PropertyType != typeof(System.Collections.Immutable.ImmutableArray<DiagnosticDescriptor>))
            throw new InvalidOperationException("The compiler plug-in public member baseline changed.");
        var xmlPath = Path.ChangeExtension(assembly.Location, ".xml");
        var xml = XDocument.Load(xmlPath).Root!.Element("members")!.Elements("member").ToDictionary(m => (string)m.Attribute("name")!);
        var signatures = new Dictionary<string, string>(StringComparer.Ordinal)
        {
            ["T:NativeWeave.Analyzers.NativeWeaveAnalyzer"] = "public sealed class NativeWeaveAnalyzer : DiagnosticAnalyzer",
            ["M:NativeWeave.Analyzers.NativeWeaveAnalyzer.#ctor"] = "public NativeWeaveAnalyzer()",
            ["P:NativeWeave.Analyzers.NativeWeaveAnalyzer.SupportedDiagnostics"] = "public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics { get; }",
            ["M:NativeWeave.Analyzers.NativeWeaveAnalyzer.Initialize(Microsoft.CodeAnalysis.Diagnostics.AnalysisContext)"] = "public override void Initialize(AnalysisContext context)"
        };
        if (signatures.Keys.Any(id => !xml.ContainsKey(id))) throw new InvalidOperationException("XML is missing an exact compiled public symbol.");
        var lines = new List<string> { "# NativeWeave analyzer compiler API", "", "Generated by `tests/Analyzers --api-reference` from the compiled plug-in and XML. This is a compiler extension seam, with no application runtime API or native operation.", "" };
        foreach (var item in signatures)
        {
            var member = xml[item.Key];
            if (string.IsNullOrWhiteSpace(member.Element("summary")?.Value)) throw new InvalidOperationException("Missing summary: " + item.Key);
            if (item.Key.Contains("Initialize", StringComparison.Ordinal) && (string?)member.Element("param")?.Attribute("name") != "context")
                throw new InvalidOperationException("Parameter XML drift.");
            if (item.Key.StartsWith("P:", StringComparison.Ordinal) && member.Element("value") == null) throw new InvalidOperationException("Missing property value XML.");
            lines.Add("## `" + item.Key + "`"); lines.Add(""); lines.Add("```csharp"); lines.Add(item.Value); lines.Add("```"); lines.Add("");
            foreach (var tag in member.Elements()) { lines.Add("**" + tag.Name.LocalName + ":** " + string.Join(" ", tag.Value.Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries))); lines.Add(""); }
        }
        File.WriteAllText(output, string.Join("\n", lines));
        Console.WriteLine("Compiled analyzer API/XML/reference: 4 exact symbols; no application runtime API.");
    }
}
