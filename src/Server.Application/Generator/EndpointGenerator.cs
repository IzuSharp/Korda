using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace NativeWeave.Server.Generator;

/// <summary>Emits static calls to the supported Server routes and declared JSON codecs, without runtime argument discovery.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class EndpointGenerator : IIncrementalGenerator
{
    private const string Prefix = "NativeWeave.Server.";
    private static readonly DiagnosticDescriptor MissingJson = new("NWAPI-S001", "Static JSON metadata required", "{0}: declare exactly one JsonSerializable context for {1}; generated endpoint binding never creates a runtime serializer", "NativeWeave.Server", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor Shape = new("NWAPI-S002", "Unsupported endpoint shape", "{0}: {1}; use an explicit RequestContext handler or a supported static endpoint declaration", "NativeWeave.Server", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor Binding = new("NWAPI-S003", "Explicit parameter binding required", "{0}: {1}; annotate RouteParameter, QueryParameter, HeaderParameter, BodyParameter or ServiceParameter explicitly", "NativeWeave.Server", DiagnosticSeverity.Error, true);
    private static readonly SymbolDisplayFormat Full = SymbolDisplayFormat.FullyQualifiedFormat.WithMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers | SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier | SymbolDisplayMiscellaneousOptions.UseSpecialTypes);

    /// <summary>Registers attributed endpoints and source-declared JSON contexts in the input compilation.</summary>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var endpoints = context.SyntaxProvider.ForAttributeWithMetadataName(Prefix + "ServerEndpointsAttribute",
            static (node, _) => node is ClassDeclarationSyntax,
            static (input, _) => (INamedTypeSymbol)input.TargetSymbol);
        var json = context.SyntaxProvider.ForAttributeWithMetadataName("System.Text.Json.Serialization.JsonSerializableAttribute",
            static (node, _) => node is ClassDeclarationSyntax,
            static (input, _) => (INamedTypeSymbol)input.TargetSymbol).Collect();
        context.RegisterSourceOutput(endpoints.Combine(json), static (output, input) => Emit(output, input.Left, input.Right));
    }

    private static void Emit(SourceProductionContext output, INamedTypeSymbol type, ImmutableArray<INamedTypeSymbol> json)
    {
        output.CancellationToken.ThrowIfCancellationRequested();
        if (!type.IsStatic || type.TypeParameters.Length != 0 || type.ContainingType is not null ||
            type.DeclaringSyntaxReferences.Any(x => x.GetSyntax(output.CancellationToken) is not ClassDeclarationSyntax declaration || !declaration.Modifiers.Any(SyntaxKind.PartialKeyword)))
        { Report(output, Shape, type, type.Name, "the endpoint container must be a top-level static partial non-generic class"); return; }
        if (type.GetMembers("Map").Length != 0)
        { Report(output, Shape, type, type.Name, "Map is reserved for generated registration"); return; }
        var methods = type.GetMembers().OfType<IMethodSymbol>().Where(x => x.GetAttributes().Any(a => Is(a, "ServerRouteAttribute"))).OrderBy(x => x.ToDisplayString(), StringComparer.Ordinal).ToArray();
        var registrations = new StringBuilder();
        bool valid = true;
        int id = 0;
        foreach (var method in methods)
        {
            output.CancellationToken.ThrowIfCancellationRequested();
            if (!TryMethod(output, method, json, registrations, ref id)) valid = false;
        }
        if (!valid) return;
        string access = type.DeclaredAccessibility == Accessibility.Public ? "public" : "internal";
        var code = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        if (!type.ContainingNamespace.IsGlobalNamespace) code.Append("namespace ").Append(type.ContainingNamespace.ToDisplayString()).Append(";\n");
        code.Append(access).Append(" static partial class @").Append(type.Name).Append("\n{\n")
            .Append("    /// <summary>Registers the source-declared handlers through static typed calls before application startup.</summary>\n")
            .Append("    /// <param name=\"routes\">The mutable application or group routes.</param>\n")
            .Append("    public static void Map(global::NativeWeave.Server.ServerRoutes routes)\n    {\n")
            .Append("        global::System.ArgumentNullException.ThrowIfNull(routes);\n").Append(registrations).Append("    }\n")
            .Append(Helpers).Append("}\n");
        output.AddSource(type.ToDisplayString().Replace('.', '_') + ".Endpoints.g.cs", SourceText.From(code.ToString(), Encoding.UTF8));
    }

    private static bool TryMethod(SourceProductionContext output, IMethodSymbol method, ImmutableArray<INamedTypeSymbol> json, StringBuilder registrations, ref int nextId)
    {
        bool valid = true;
        if (!method.IsStatic || method.IsGenericMethod || method.ReturnsByRef || method.ReturnsByRefReadonly || method.IsAsync && method.ReturnsVoid)
        { Report(output, Shape, method, method.Name, "handlers must be static, closed, and cannot return by reference or async void"); return false; }
        ITypeSymbol returns = method.ReturnType;
        bool task = returns is INamedTypeSymbol namedTask && namedTask.Name == "Task" && namedTask.ContainingNamespace.ToDisplayString() == "System.Threading.Tasks";
        if (task && returns is INamedTypeSymbol n && n.TypeArguments.Length == 1) returns = n.TypeArguments[0];
        bool empty = method.ReturnsVoid || task && returns is INamedTypeSymbol t && t.TypeArguments.Length == 0;
        bool result = returns.ToDisplayString() == Prefix + "ServerResult";
        if (!empty && Unsupported(returns))
        { Report(output, Shape, method, method.Name, "the return type is not a supported static result or DTO"); return false; }
        string? outputInfo = null;
        if (!empty && !result && (outputInfo = JsonInfo(output, method, returns, json)) is null) valid = false;
        int contexts = 0, tokens = 0, bodies = 0;
        var lines = new StringBuilder();
        var args = new List<string>();
        foreach (var parameter in method.Parameters)
        {
            string local = "__p" + args.Count;
            args.Add(local);
            if (parameter.RefKind != RefKind.None || Unsupported(parameter.Type))
            { Report(output, Shape, parameter, parameter.Name, "ref/out/in, ref structs, dynamic, delegates and open types are not supported"); valid = false; continue; }
            string actual = parameter.Type.ToDisplayString();
            var attributes = parameter.GetAttributes().Where(x => x.AttributeClass?.ContainingNamespace.ToDisplayString() == "NativeWeave.Server" && x.AttributeClass.Name.EndsWith("ParameterAttribute", StringComparison.Ordinal)).ToArray();
            if (actual == Prefix + "RequestContext" || actual == "System.Threading.CancellationToken")
            {
                if (attributes.Length != 0 || (actual == Prefix + "RequestContext" ? ++contexts : ++tokens) > 1)
                { Report(output, Binding, parameter, parameter.Name, "context/token cannot be duplicated or carry another binding"); valid = false; }
                lines.Append("            var ").Append(local).Append(" = ").Append(actual == Prefix + "RequestContext" ? "__context" : "__token").Append(";\n");
                continue;
            }
            if (attributes.Length != 1)
            { Report(output, Binding, parameter, parameter.Name, "one explicit parameter source is required"); valid = false; continue; }
            var attribute = attributes[0];
            string name = attribute.ConstructorArguments.Length == 1 && attribute.ConstructorArguments[0].Value is string specified ? specified : parameter.Name;
            string source = attribute.AttributeClass!.Name;
            bool optional = parameter.NullableAnnotation == NullableAnnotation.Annotated || parameter.HasExplicitDefaultValue || parameter.Type is INamedTypeSymbol nt && nt.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T;
            if (source == "ServiceParameterAttribute")
            {
                lines.Append("            var ").Append(local).Append(" = global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<").Append(Type(parameter.Type)).Append(">(__context.Services);\n");
                continue;
            }
            if (source == "BodyParameterAttribute")
            {
                if (++bodies > 1) { Report(output, Binding, parameter, parameter.Name, "only one body parameter is allowed"); valid = false; continue; }
                string? info = JsonInfo(output, parameter, parameter.Type, json);
                if (info is null) { valid = false; continue; }
                lines.Append("            __CheckJsonMedia(__context, ").Append(optional ? "true" : "false").Append(");\n")
                    .Append("            var ").Append(local).Append(" = ");
                if (optional) lines.Append("__context.Request.ContentLength == 0 ? ").Append(Default(parameter)).Append(" : ");
                lines.Append("await __context.Request.ReadJsonAsync(").Append(info).Append(", __token).ConfigureAwait(false);\n");
                if (!optional) lines.Append("            if (").Append(local).Append(" is null) throw new global::NativeWeave.Server.RequestBindingException(\"body\", \"A non-null JSON body is required.\");\n");
                continue;
            }
            bool array = parameter.Type is IArrayTypeSymbol;
            ITypeSymbol scalar = array ? ((IArrayTypeSymbol)parameter.Type).ElementType : Unwrap(parameter.Type);
            if (array && source != "QueryParameterAttribute" || !Parsable(scalar))
            { Report(output, Shape, parameter, parameter.Name, "scalar binding requires IParsable<T>; arrays are allowed only for explicit query parameters"); valid = false; continue; }
            string values = source switch { "RouteParameterAttribute" => "__context.Request.RouteValues", "QueryParameterAttribute" => "__context.Request.Query", "HeaderParameterAttribute" => "__context.Request.Headers", _ => "" };
            if (values.Length == 0) { Report(output, Binding, parameter, parameter.Name, "unknown binding source"); valid = false; continue; }
            if (source == "RouteParameterAttribute" && method.GetAttributes().Where(x => Is(x, "ServerRouteAttribute")).Any(x => x.ConstructorArguments.Length == 2 && x.ConstructorArguments[1].Value is string pattern && !pattern.Contains("{" + name + "}") && !pattern.Contains("{*" + name + "}")))
            { Report(output, Binding, parameter, parameter.Name, "route parameter does not occur in every declared pattern"); valid = false; continue; }
            lines.Append("            var __v").Append(local).Append(" = ").Append(values).Append(source == "HeaderParameterAttribute" ? "[" : ".GetValues(").Append(Literal(name)).Append(source == "HeaderParameterAttribute" ? "];\n" : ");\n")
                .Append("            ").Append(Type(parameter.Type)).Append(' ').Append(local).Append(" = ");
            if (optional && !array) lines.Append("__v").Append(local).Append(".Count == 0 ? ").Append(Default(parameter)).Append(" : ");
            lines.Append(array ? "__ParseMany<" : "__ParseOne<").Append(Type(scalar)).Append(">(__v").Append(local).Append(", ").Append(Literal(name)).Append(");\n");
        }
        if (empty && contexts == 0)
        { Report(output, Shape, method, method.Name, "void/Task handlers require RequestContext for explicit response access"); valid = false; }
        if (!valid) return false;
        bool asynchronous = task || bodies > 0;
        string call = "@" + method.Name + "(" + string.Join(", ", args) + ")";
        foreach (var route in method.GetAttributes().Where(x => Is(x, "ServerRouteAttribute")))
        {
            if (route.ConstructorArguments.Length != 2 || route.ConstructorArguments[0].Value is not string verb || route.ConstructorArguments[1].Value is not string pattern)
            { Report(output, Binding, method, method.Name, "route requires constant method and pattern strings"); return false; }
            registrations.Append("        // Source handler ").Append(nextId++).Append(": ").Append(method.Name).Append("\n")
                .Append("        routes.").Append(empty ? "MapRaw" : "MapMethods").Append('(').Append(Literal(pattern)).Append(", new string[] { ").Append(Literal(verb)).Append(" }, ")
                .Append(asynchronous ? "async " : "").Append("(__context, __token) =>\n        {\n").Append(lines);
            if (empty)
            {
                registrations.Append("            ").Append(task ? "await " : "").Append(call).Append(task ? ".ConfigureAwait(false);\n" : ";\n");
                if (!asynchronous) registrations.Append("            return global::System.Threading.Tasks.Task.CompletedTask;\n");
            }
            else
            {
                string value = task ? "await " + call + ".ConfigureAwait(false)" : call;
                registrations.Append("            var __result = ").Append(value).Append(";\n");
                if (!result) value = "global::NativeWeave.Server.Results.Json(__result, " + outputInfo + ")"; else value = "__result";
                registrations.Append("            return ").Append(asynchronous ? value : "global::System.Threading.Tasks.Task.FromResult<global::NativeWeave.Server.ServerResult>(" + value + ")").Append(";\n");
            }
            registrations.Append("        });\n");
        }
        return true;
    }

    private static string? JsonInfo(SourceProductionContext output, ISymbol location, ITypeSymbol type, ImmutableArray<INamedTypeSymbol> contexts)
    {
        var matches = contexts.Where(c => c.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == "System.Text.Json.Serialization.JsonSerializableAttribute" && a.ConstructorArguments.Length > 0 && a.ConstructorArguments[0].Value is ITypeSymbol declared && SymbolEqualityComparer.Default.Equals(declared, type))).Distinct(SymbolEqualityComparer.Default).ToArray();
        if (matches.Length != 1 || type.SpecialType == SpecialType.System_Object || type.TypeKind == TypeKind.Dynamic)
        { Report(output, MissingJson, location, location.Name, Type(type)); return null; }
        // Metadata is declared in input source. No generator reads another generator's output.
        return "((global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<" + Type(type) + ">)" + matches[0]!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + ".Default.GetTypeInfo(typeof(" + Type(type.WithNullableAnnotation(NullableAnnotation.None)) + "))!)";
    }
    private static bool Unsupported(ITypeSymbol type) => type.IsRefLikeType || type.TypeKind is TypeKind.Dynamic or TypeKind.Pointer or TypeKind.FunctionPointer or TypeKind.TypeParameter or TypeKind.Delegate || type.SpecialType == SpecialType.System_Object || type is INamedTypeSymbol n && n.TypeArguments.Any(Unsupported);
    private static bool Parsable(ITypeSymbol type) => type.AllInterfaces.Any(x => x.OriginalDefinition.ToDisplayString() == "System.IParsable<TSelf>" && SymbolEqualityComparer.Default.Equals(x.TypeArguments[0], type));
    private static ITypeSymbol Unwrap(ITypeSymbol type) => type is INamedTypeSymbol n && n.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T ? n.TypeArguments[0] : type.WithNullableAnnotation(NullableAnnotation.None);
    private static string Type(ITypeSymbol type) => type.ToDisplayString(Full);
    private static string Literal(string text) => SymbolDisplay.FormatLiteral(text, true);
    private static bool Is(AttributeData attribute, string name) => attribute.AttributeClass?.ToDisplayString() == Prefix + name;
    private static string Default(IParameterSymbol parameter)
    {
        if (!parameter.HasExplicitDefaultValue || parameter.ExplicitDefaultValue is null) return "default(" + Type(parameter.Type) + ")";
        object value = parameter.ExplicitDefaultValue;
        string literal = value is string s ? Literal(s) : value is char c ? SymbolDisplay.FormatLiteral(c, true) : value is bool b ? (b ? "true" : "false") : Convert.ToString(value, CultureInfo.InvariantCulture)!;
        return "(" + Type(parameter.Type) + ")(" + literal + ")";
    }
    private static void Report(SourceProductionContext output, DiagnosticDescriptor descriptor, ISymbol symbol, params object[] args)
    {
        // The pinned IDs contain a hyphen. Roslyn rejects that spelling in
        // SourceProductionContext.ReportDiagnostic, but the compiler's documented
        // ObsoleteAttribute.DiagnosticId accepts it. An inaccessible generated
        // error sentinel preserves the exact contract ID and mapped input location.
        // No sentinel is emitted for a valid handler and no public API is added.
        string message = descriptor.Id + ": " + string.Format(CultureInfo.InvariantCulture, descriptor.MessageFormat.ToString(CultureInfo.InvariantCulture), args);
        var location = symbol.Locations.FirstOrDefault(x => x.IsInSource)?.GetLineSpan();
        string identity = symbol.ContainingSymbol?.ToDisplayString() + "|" + symbol.ToDisplayString() + "|" + location?.StartLinePosition.ToString() + "|" + descriptor.Id + "|" + message;
        ulong hash = 14695981039346656037UL;
        foreach (char ch in identity) hash = unchecked((hash ^ ch) * 1099511628211UL);
        string suffix = hash.ToString("x16", CultureInfo.InvariantCulture);
        int line = (location?.StartLinePosition.Line ?? 0) + 1;
        int column = location?.StartLinePosition.Character ?? 0;
        string path = location?.Path ?? "GeneratedEndpointBinding";
        string code = "// <auto-generated/>\nnamespace NativeWeave.GeneratedDiagnostics { internal static class E" + suffix + " {\n" +
            "[global::System.Obsolete(" + Literal(message) + ", true, DiagnosticId = " + Literal(descriptor.Id) + ")] private static void InvalidBinding() {}\n" +
            "private static void Validate() {\n#line " + line.ToString(CultureInfo.InvariantCulture) + " " + Literal(path) + "\n" +
            new string(' ', column) + "InvalidBinding();\n#line default\n} } }\n";
        output.AddSource("EndpointBindingError." + suffix + ".g.cs", SourceText.From(code, Encoding.UTF8));
    }

    private const string Helpers = @"
    private static T __ParseOne<T>(global::System.Collections.Generic.IReadOnlyList<string> values, string name) where T : global::System.IParsable<T>
    {
        if (values.Count != 1 || !T.TryParse(values[0], global::System.Globalization.CultureInfo.InvariantCulture, out var value))
            throw new global::NativeWeave.Server.RequestBindingException(name, ""A required value is missing, repeated or malformed."");
        return value;
    }
    private static T[] __ParseMany<T>(global::System.Collections.Generic.IReadOnlyList<string> values, string name) where T : global::System.IParsable<T>
    {
        var result = new T[values.Count];
        for (int i = 0; i < values.Count; i++)
            if (!T.TryParse(values[i], global::System.Globalization.CultureInfo.InvariantCulture, out result[i]!))
                throw new global::NativeWeave.Server.RequestBindingException(name, ""A query array element is malformed."");
        return result;
    }
    private static void __CheckJsonMedia(global::NativeWeave.Server.RequestContext context, bool optional)
    {
        if (optional && context.Request.ContentLength == 0) return;
        string? media = context.Request.ContentType?.Split(';')[0].Trim();
        if (media is null || !(media.Equals(""application/json"", global::System.StringComparison.OrdinalIgnoreCase) || media.StartsWith(""application/"", global::System.StringComparison.OrdinalIgnoreCase) && media.EndsWith(""+json"", global::System.StringComparison.OrdinalIgnoreCase)) ||
            context.Request.Headers.GetSingle(""Content-Encoding"") is { } encoding && !encoding.Equals(""identity"", global::System.StringComparison.OrdinalIgnoreCase))
            throw new global::NativeWeave.Server.ServerException(""unsupported_media_type"", ""Static JSON binding requires an uncompressed JSON media type."");
    }
";
}
