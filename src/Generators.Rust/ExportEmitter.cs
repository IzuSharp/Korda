using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using NativeWeave.Generators.Model;

namespace NativeWeave.Generators.Rust;

/// <summary>Produces deterministic C declarations and Rust layout assertions from A09's validated model.</summary>
internal static class ExportEmitter
{
    internal static (string Header, string Assertions, string Manifest) Emit(ReadOnlySpan<byte> sidecar,
        ReadOnlySpan<byte> adapter, ReadOnlySpan<byte> inventory, IEnumerable<string> linked,
        CancellationToken cancellationToken = default) =>
        Emit(BindingReader.Read(sidecar, "sidecar", cancellationToken), adapter, inventory, linked, cancellationToken);

    internal static (string Header, string Assertions, string Manifest) Emit(BindingDescription model,
        ReadOnlySpan<byte> adapter, ReadOnlySpan<byte> inventory, IEnumerable<string> linked,
        CancellationToken cancellationToken = default)
    {
        cancellationToken.ThrowIfCancellationRequested();
        using var canonical = JsonDocument.Parse(model.GetCanonicalBytes());
        var digest = Convert.ToHexStringLower(SHA256.HashData(adapter));
        if (canonical.RootElement.GetProperty("provenance").GetProperty("adapter_sha256").GetString() != digest)
            throw new BindingValidationException("NWGEN001", new("adapter", "$", 1, 1), "Adapter bytes changed; regenerate the sidecar and parser inventory together.");
        var parsed = SourceInventory.Read(inventory, digest);
        model.VerifyInventories(parsed, model.Symbols, linked, cancellationToken);
        var header = new StringBuilder("/* Generated by NativeWeave A11; do not edit. */\n#ifndef NATIVEWEAVE_GENERATED_");
        header.Append(model.Digest.ToUpperInvariant()).Append("\n#define NATIVEWEAVE_GENERATED_").Append(model.Digest.ToUpperInvariant())
            .Append("\n#include <stdint.h>\n#include <stddef.h>\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n");
        var assertions = new StringBuilder("// Generated by NativeWeave A11; no runtime execution.\n// schema-sha256: ").Append(model.Digest).Append('\n');
        foreach (var owner in model.Owners)
            header.Append("typedef struct ").Append(owner.Kind).Append(' ').Append(owner.Kind).Append(";\n");
        foreach (var record in model.Records)
        {
            cancellationToken.ThrowIfCancellationRequested();
            header.Append("typedef struct ").Append(record.Name).Append(" {\n");
            foreach (var field in record.Fields)
                header.Append("    ").Append(CType(field.Type)).Append(' ').Append(field.Name).Append(";\n");
            header.Append("} ").Append(record.Name).Append(";\n");
            header.Append("_Static_assert(sizeof(").Append(record.Name).Append(") == ").Append(record.Size).Append(", \"size ").Append(record.Name).Append("\");\n");
            header.Append("_Static_assert(_Alignof(").Append(record.Name).Append(") == ").Append(record.Alignment).Append(", \"align ").Append(record.Name).Append("\");\n");
            assertions.Append("const _: () = {\n    assert!(core::mem::size_of::<").Append(record.Name).Append(">() == ").Append(record.Size).Append(");\n    assert!(core::mem::align_of::<").Append(record.Name).Append(">() == ").Append(record.Alignment).Append(");\n");
            foreach (var field in record.Fields)
            {
                header.Append("_Static_assert(offsetof(").Append(record.Name).Append(", ").Append(field.Name).Append(") == ").Append(field.Offset).Append(", \"offset ").Append(field.Name).Append("\");\n");
                assertions.Append("    assert!(core::mem::offset_of!(").Append(record.Name).Append(", ").Append(RustIdentifier(field.Name)).Append(") == ").Append(field.Offset).Append(");\n");
            }
            assertions.Append("};\n");
        }
        foreach (var export in model.Exports)
        {
            cancellationToken.ThrowIfCancellationRequested();
            header.Append("/* ").Append(export.ErrorProfile).Append("; ").Append(export.ThreadProfile).Append("; ").Append(export.Reentrancy).Append(". */\n")
                .Append(CType(export.ReturnType)).Append(' ').Append(export.Symbol).Append('(')
                .Append(export.Parameters.Length == 0 ? "void" : string.Join(", ", export.Parameters.Select(p => CType(p.Type) + " " + p.Name))).Append(");\n");
            // A typed function item proves ABI, arity and all parameter/return types. The Rust
            // compiler checks this against the actual adapter declarations, not an inferred layout.
            assertions.Append("const _: unsafe extern \"C\" fn(")
                .Append(string.Join(", ", export.Parameters.Select(p => RustType(p.Type)))).Append(')');
            if (export.ReturnType != "void") assertions.Append(" -> ").Append(RustType(export.ReturnType));
            assertions.Append(" = ").Append(RustIdentifier(export.Symbol)).Append(";\n");
        }
        header.Append("#ifdef __cplusplus\n}\n#endif\n#endif\n");
        var h = header.ToString(); var a = assertions.ToString();
        var manifest = JsonSerializer.Serialize(new
        {
            schema_version = 1,
            generator = "NativeWeave.Generators.Rust",
            generator_version = "0.1.0",
            model.Module,
            schema_sha256 = model.Digest,
            adapter_sha256 = digest,
            parsed_inventory_sha256 = Convert.ToHexStringLower(SHA256.HashData(inventory)),
            header_sha256 = Hash(h),
            assertions_sha256 = Hash(a),
            symbols = model.Symbols.ToArray(),
            target = canonical.RootElement.GetProperty("module").GetProperty("target").GetString(),
            upstream = canonical.RootElement.GetProperty("provenance").GetProperty("upstream")
        }, new JsonSerializerOptions { WriteIndented = true }) + "\n";
        return (h, a, manifest);
    }

    internal static string CType(string type)
    {
        if (type.StartsWith("const:", StringComparison.Ordinal))
            return type[6..].Contains(':') ? CType(type[6..]) + " const *" : "const " + CType(type[6..]) + " *";
        if (type.StartsWith("mut:", StringComparison.Ordinal)) return CType(type[4..]) + " *";
        return type switch
        {
            "u8" => "uint8_t", "i8" => "int8_t", "u16" => "uint16_t", "i16" => "int16_t",
            "u32" => "uint32_t", "i32" => "int32_t", "u64" => "uint64_t", "i64" => "int64_t",
            "usize" => "uintptr_t", "f32" => "float", "f64" => "double", "void" => "void", _ => type
        };
    }
    private static string RustType(string type) => type.StartsWith("const:", StringComparison.Ordinal)
        ? "*const " + RustType(type[6..]) : type.StartsWith("mut:", StringComparison.Ordinal)
        ? "*mut " + RustType(type[4..]) : type == "void" ? "core::ffi::c_void" : RustIdentifier(type);
    private static string RustIdentifier(string name) => name is "type" or "match" or "ref" or "self" or "loop" or "mod" or "fn" or "move" or "where" or "async" or "await" or "gen" ? "r#" + name : name;
    private static string Hash(string value) => Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(value)));
}
