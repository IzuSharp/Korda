using System.Security;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using NativeWeave.Generators.Model;

namespace NativeWeave.Generators.CSharp;

/// <summary>Maintainer-only generation before C# compilation; never a peer LibraryImport source generator.</summary>
internal static class BindingEmitter
{
    internal static (string Source, string Metadata) Emit(ReadOnlySpan<byte> sidecar, ReadOnlySpan<byte> adapter,
        ReadOnlySpan<byte> inventory, IEnumerable<string> linked, string library, string? targetNamespace = null,
        CancellationToken cancellationToken = default)
    {
        var model = BindingReader.Read(sidecar, "sidecar", cancellationToken);
        using var canonical = JsonDocument.Parse(model.GetCanonicalBytes());
        var digest = Convert.ToHexStringLower(SHA256.HashData(adapter));
        if (canonical.RootElement.GetProperty("provenance").GetProperty("adapter_sha256").GetString() != digest)
            Fail("NWGEN001", "Adapter source changed; regenerate the validated sidecar and parser inventory.");
        var parsed = SourceInventory.Read(inventory, digest);
        model.VerifyInventories(parsed, model.Symbols, linked, cancellationToken);
        if (library.Length is 0 or > 128 || !library.All(x => char.IsAsciiLetterOrDigit(x) || x is '_' or '.' or '-'))
            Fail("NWGEN001", "Use a bounded logical native library name, without paths or source snippets.");
        var ns = targetNamespace ?? "NativeWeave.Generated.M_" + Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(model.Module)));
        if (ns.Length > 512 || ns.Split('.').Any(x => !BindingDescription.IsIdentifier(x)))
            Fail("NWGEN001", "Use an explicit non-generic C# namespace with ASCII identifier segments.");
        foreach (var owner in model.Owners)
            if (owner.ReleaseExecutor != "calling-thread")
                Fail("NWOWN001", "Automatic wrappers support bounded nonblocking calling-thread release only; supply a separately accepted affinity adapter for " + owner.Kind + ".");
        if (model.Exports.Any(x => x.ThreadProfile != "free-threaded"))
            Fail("NWABI002", "Automatic calls support the free-threaded profile; serialized, owner-thread or externally-driven exports require an explicit completed dispatch adapter.");
        if (model.Exports.SelectMany(x => x.Parameters).Any(p => p.Owner.Length != 0 && p.BorrowEnd is not ("call" or "transfer-success")))
            Fail("NWASYNC001", "An owner borrow beyond the call requires an explicit retained-owner adapter; automatic calls cannot end that lease at return.");
        var typeNames = model.Records.Select(x => x.Name).Concat(model.Owners.Select(x => "Owner_" + x.Kind))
            .Concat(model.Operations.SelectMany(x => new[] { "Operation_" + x.Name, "IOperationSetup_" + x.Name }))
            .Concat(["NativeMethods", "OwnedCalls", "ReverseEntries", "BindingCallbacks", "BindingOperations"]).ToArray();
        if (typeNames.Distinct(StringComparer.Ordinal).Count() != typeNames.Length)
            Fail("NWGEN001", "Record and generated adapter identities collide; choose distinct native type identities.");
        if (model.Records.Any(r => r.Fields.Any(f => f.Name == r.Name)) ||
            model.Exports.Any(e => e.Symbol is "NativeMethods" or "OwnedCalls" or "ReverseEntries"))
            Fail("NWGEN001", "A member name collides with its generated C# enclosing type.");
        if (typeNames.Any(FrameworkNames.Contains))
            Fail("NWGEN001", "A native type shadows a framework type used by the generated adapter; choose a distinct ABI type spelling.");
        var source = new StringBuilder("// <auto-generated />\n// nativeweave-schema-sha256:").Append(model.Digest)
            .Append("\n#nullable enable\nusing System;\nusing System.Runtime.CompilerServices;\nusing System.Runtime.InteropServices;\nusing System.Threading.Tasks;\nnamespace ")
            .Append(string.Join('.', ns.Split('.').Select(Id))).Append(";\n\n");
        foreach (var record in model.Records)
        {
            cancellationToken.ThrowIfCancellationRequested();
            source.Append("/// <summary>Fixed ").Append(record.Size).Append("-byte native record; natural alignment ").Append(record.Alignment).Append(".</summary>\n")
                .Append("/// <remarks>Internal storage; pointers and padding are never a public application API.</remarks>\n[StructLayout(LayoutKind.Sequential)]\ninternal struct ").Append(Id(record.Name)).Append("\n{\n");
            foreach (var field in record.Fields)
                source.Append("    /// <summary>").Append(field.Reserved ? "Reserved; initialize to zero." : "Wire field at byte offset " + field.Offset + ".")
                    .Append("</summary>\n    internal ").Append(Type(field.Type, model)).Append(' ').Append(Id(field.Name)).Append(";\n");
            source.Append("}\n\n");
        }
        source.Append("/// <summary>Exact raw engine imports; all ownership remains in the typed adapter.</summary>\ninternal static unsafe partial class NativeMethods\n{\n");
        foreach (var export in model.Exports)
        {
            cancellationToken.ThrowIfCancellationRequested();
            Docs(source, export, "    ");
            source.Append("    [LibraryImport(\"").Append(library).Append("\", EntryPoint = \"").Append(export.Symbol).Append("\")]\n")
                .Append("    [UnmanagedCallConv(CallConvs = new[] { typeof(CallConvCdecl) })]\n    internal static partial ")
                .Append(Type(export.ReturnType, model)).Append(' ').Append(Id(export.Symbol)).Append('(')
                .Append(string.Join(", ", export.Parameters.Select(p => Type(p.Type, model) + " " + Id(p.Name)))).Append(");\n\n");
        }
        source.Append("}\n\n");
        foreach (var owner in model.Owners)
        {
            var name = "Owner_" + owner.Kind;
            source.Append("/// <summary>Private identity owner; D04 admission and retirement are supplied by A03.</summary>\n")
                .Append("/// <remarks>Dispose closes new admission. DisposeAsync waits for actual lease retirement; no module unload occurs.</remarks>\n")
                .Append("internal sealed class ").Append(name).Append(" : IDisposable, IAsyncDisposable\n{\n")
                .Append("    internal readonly global::NativeWeave.Interop.Lifetime.NativeResourceOwner Resource;\n")
                .Append("    private ").Append(name).Append("(Handle handle) { Resource = new(handle); }\n")
                .Append("    internal static ").Append(name).Append(" Adopt(ref nint address)\n    {\n")
                .Append("        if (address == 0) throw new InvalidOperationException(\"Successful creation returned no owner.\");\n")
                .Append("        var handle = new Handle(address);\n        address = 0;\n        try { return new ").Append(name).Append("(handle); }\n")
                .Append("        catch { handle.Dispose(); throw; }\n    }\n")
                .Append("    public void Dispose() => Resource.Dispose();\n    public ValueTask DisposeAsync() => Resource.DisposeAsync();\n")
                .Append("    private sealed class Handle : SafeHandle\n    {\n")
                .Append("        internal Handle(nint address) : base(0, true) { SetHandle(address); }\n")
                .Append("        public override bool IsInvalid => handle == 0;\n")
                .Append("        protected override bool ReleaseHandle() { NativeMethods.").Append(Id(owner.Release)).Append("(handle); return true; }\n    }\n}\n\n");
        }
        source.Append("/// <summary>Internal typed calls; A03 supplies all logical admission and physical lease algorithms.</summary>\ninternal static unsafe class OwnedCalls\n{\n");
        foreach (var export in model.Exports.Where(x => !model.Owners.Any(o => o.Release == x.Symbol)))
        {
            cancellationToken.ThrowIfCancellationRequested();
            var inputOwners = export.Parameters.Where(p => p.Owner.Length != 0 && p.BorrowEnd != "transfer-success").ToArray();
            var outputOwners = export.Parameters.Where(p => p.BorrowEnd == "transfer-success").ToArray();
            var local = LocalPrefix(export);
            Docs(source, export, "    ");
            source.Append("    internal static ").Append(Type(export.ReturnType, model)).Append(' ').Append(Id(export.Symbol)).Append('(')
                .Append(string.Join(", ", export.Parameters.Select(p => p.BorrowEnd == "transfer-success" ? "out Owner_" + p.Owner + "? " + Id(p.Name) :
                    p.Owner.Length != 0 ? OwnerParameter(p) : Type(p.Type, model) + " " + Id(p.Name)))).Append(")\n    {\n");
            foreach (var parameter in inputOwners)
            {
                if (!parameter.Nullable)
                    source.Append("        ArgumentNullException.ThrowIfNull(").Append(Id(parameter.Name)).Append(");\n");
                source.Append("        bool ").Append(local).Append("lease_").Append(parameter.Name).Append(" = false;\n");
            }
            foreach (var parameter in outputOwners)
                source.Append("        ").Append(Id(parameter.Name)).Append(" = null;\n        nint ").Append(local).Append("raw_").Append(parameter.Name).Append(" = 0;\n");
            if (outputOwners.Length != 0) source.Append("        bool ").Append(local).Append("completed = false;\n");
            source.Append("        try\n        {\n");
            foreach (var parameter in inputOwners)
                source.Append("            nint ").Append(local).Append("raw_").Append(parameter.Name).Append(" = ")
                    .Append(parameter.Nullable ? Id(parameter.Name) + " is null ? 0 : " : "")
                    .Append(Id(parameter.Name)).Append(".Resource.Acquire(ref ").Append(local).Append("lease_").Append(parameter.Name).Append(");\n");
            source.Append("            ");
            if (export.ReturnType != "void") source.Append("uint ").Append(local).Append("status = ");
            source.Append("NativeMethods.").Append(Id(export.Symbol)).Append('(')
                .Append(string.Join(", ", export.Parameters.Select(p => p.BorrowEnd == "transfer-success" ? "&" + local + "raw_" + p.Name : p.Owner.Length != 0 ? local + "raw_" + p.Name : Id(p.Name)))).Append(");\n");
            foreach (var parameter in outputOwners)
                source.Append("            if (").Append(local).Append("status == 0) ").Append(Id(parameter.Name)).Append(" = Owner_").Append(parameter.Owner).Append(".Adopt(ref ").Append(local).Append("raw_").Append(parameter.Name).Append(");\n")
                    .Append("            else if (").Append(local).Append("raw_").Append(parameter.Name).Append(" != 0) throw new InvalidOperationException(\"Native failure transferred an owner.\");\n");
            if (outputOwners.Length != 0) source.Append("            ").Append(local).Append("completed = true;\n");
            if (export.ReturnType != "void") source.Append("            return ").Append(local).Append("status;\n");
            source.Append("        }\n        finally\n        {\n");
            // Unadopted outputs belong to the creating module. A failed wrapper allocation, status
            // mapping or malformed failure output cannot strand the native ownership right.
            foreach (var parameter in outputOwners.Reverse())
                source.Append("            if (!").Append(local).Append("completed) ").Append(Id(parameter.Name)).Append("?.Dispose();\n")
                    .Append("            if (").Append(local).Append("raw_").Append(parameter.Name).Append(" != 0) NativeMethods.").Append(Id(model.Owners.Single(o => o.Kind == parameter.Owner).Release)).Append('(').Append(local).Append("raw_").Append(parameter.Name).Append(");\n");
            foreach (var parameter in inputOwners.Reverse())
                source.Append("            ").Append(parameter.Nullable ? "if (" + Id(parameter.Name) + " is not null) " : "")
                    .Append(Id(parameter.Name)).Append(".Resource.Release(ref ").Append(local).Append("lease_").Append(parameter.Name).Append(");\n");
            source.Append("        }\n    }\n\n");
        }
        source.Append("}\n\n");
        var callbacks = canonical.RootElement.GetProperty("callbacks").EnumerateArray().ToArray();
        if (callbacks.Length != 0)
        {
            source.Append("/// <summary>Static nongeneric reverse entries; BindingCallbacks is the fixed A06/A07 dispatch contract.</summary>\ninternal static unsafe class ReverseEntries\n{\n");
            foreach (var callback in callbacks)
            {
                var export = model.Exports.Single(e => e.Symbol == callback.GetProperty("symbol").GetString());
                var cookie = Id(export.Parameters[callback.GetProperty("cookie_index").GetInt32()].Name);
                var local = LocalPrefix(export);
                Docs(source, export, "    ");
                source.Append("    [UnmanagedCallersOnly(CallConvs = new[] { typeof(CallConvCdecl) })]\n    internal static uint ").Append(Id(export.Symbol)).Append('(')
                    .Append(string.Join(", ", export.Parameters.Select(p => Type(p.Type, model) + " " + Id(p.Name)))).Append(")\n    {\n        uint ").Append(local).Append("result = 8;\n")
                    .Append("        try { ").Append(local).Append("result = BindingCallbacks.Dispatch_").Append(export.Symbol).Append('(').Append(string.Join(", ", export.Parameters.Select(p => Id(p.Name)))).Append("); }\n")
                    .Append("        catch (Exception) { try { BindingCallbacks.Fault(").Append(cookie).Append("); } catch (Exception) { } }\n")
                    .Append("        finally\n        {\n            try { BindingCallbacks.Wake(").Append(cookie).Append("); }\n")
                    .Append("            catch (Exception) { ").Append(local).Append("result = 8; try { BindingCallbacks.Fault(").Append(cookie).Append("); } catch (Exception) { } }\n        }\n")
                    .Append("        return ").Append(local).Append("result;\n    }\n");
            }
            source.Append("}\n");
        }
        foreach (var operation in model.Operations)
        {
            cancellationToken.ThrowIfCancellationRequested();
            var start = model.Exports.Single(e => e.Symbol == operation.Start);
            var setupType = "IOperationSetup_" + operation.Name;
            var local = LocalPrefix(start);
            source.Append("\n/// <summary>D06 coordinator contract: setup/input retention, unpublished output rollback and retirement.</summary>\n")
                .Append("/// <remarks>The completed runtime supplies this internal contract. No state machine is duplicated in generated bindings. Notifications do not free retained inputs; StartExited and retirement remain separate.</remarks>\n")
                .Append("internal interface ").Append(setupType).Append("\n{\n")
                .Append("    void StartExited(uint status, bool returned);\n    void MappingFailed();\n    void RequestRetire();\n}\n")
                .Append("/// <summary>Static calls into the explicit D06 coordinator; no runtime discovery.</summary>\ninternal static unsafe class Operation_").Append(operation.Name).Append("\n{\n")
                .Append("    internal static uint Start(").Append(string.Join(", ", start.Parameters.Select(p => p.Owner.Length != 0 ? OwnerParameter(p) : Type(p.Type, model) + " " + Id(p.Name))))
                .Append(")\n    {\n        ").Append(setupType).Append(' ').Append(local).Append("setup = BindingOperations.Prepare_").Append(operation.Name).Append('(')
                .Append(string.Join(", ", start.Parameters.Select(p => Id(p.Name)))).Append(");\n        ArgumentNullException.ThrowIfNull(").Append(local).Append("setup);\n")
                .Append("        uint ").Append(local).Append("status = 11;\n        bool ").Append(local).Append("returned = false;\n        try\n        {\n            ")
                .Append(local).Append("status = OwnedCalls.").Append(Id(operation.Start)).Append('(').Append(string.Join(", ", start.Parameters.Select(p => Id(p.Name)))).Append(");\n")
                .Append("            ").Append(local).Append("returned = true;\n            return ").Append(local).Append("status;\n        }\n")
                .Append("        finally { ").Append(local).Append("setup.StartExited(").Append(local).Append("status, ").Append(local).Append("returned); }\n    }\n")
                .Append("    internal static TResult MapResult<TResult>(").Append(setupType).Append(" setup, Func<TResult> mapper)\n    {\n")
                .Append("        ArgumentNullException.ThrowIfNull(setup);\n        ArgumentNullException.ThrowIfNull(mapper);\n")
                .Append("        try { return mapper(); }\n        catch (Exception) { setup.MappingFailed(); throw; }\n        finally { setup.RequestRetire(); }\n    }\n}\n");
        }
        cancellationToken.ThrowIfCancellationRequested();
        var text = source.ToString();
        var metadata = new StringBuilder("nativeweave-metadata-v1\nmodule\t").Append(model.Module).Append("\ndigest\t").Append(model.Digest)
            .Append("\nnamespace\t").Append(ns).Append("\nlibrary\t").Append(library).Append("\nsource_sha256\t")
            .Append(Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(text)))).Append('\n');
        foreach (var record in model.Records)
        {
            metadata.Append("record\t").Append(record.Name).Append('\t').Append(record.Size).Append('\t').Append(record.Alignment).Append('\n');
            foreach (var field in record.Fields) metadata.Append("field\t").Append(record.Name).Append('\t').Append(field.Name).Append('\t').Append(field.Type).Append('\t').Append(field.Offset).Append('\n');
        }
        foreach (var export in model.Exports)
        {
            metadata.Append("export\t").Append(export.Symbol).Append('\t').Append(Type(export.ReturnType, model)).Append('\t').Append(string.Join(',', export.Parameters.Select(p => Type(p.Type, model)))).Append('\n');
            foreach (var p in export.Parameters) metadata.Append("parameter\t").Append(export.Symbol).Append('\t').Append(p.Name).Append('\t').Append(p.Type).Append('\t').Append(p.Direction).Append('\t').Append(p.BorrowEnd).Append('\t').Append(p.Owner).Append('\t').Append(p.Mutable ? '1' : '0').Append('\t').Append(p.CopyBeforeAccept ? '1' : '0').Append('\t').Append(p.MaximumBytes).Append('\n');
        }
        foreach (var o in model.Owners) metadata.Append("owner\t").Append(o.Kind).Append('\t').Append(o.Release).Append('\t').Append(o.Parent).Append('\t').Append(o.ReleaseExecutor).Append('\n');
        foreach (var c in callbacks) metadata.Append("callback\t").Append(c.GetProperty("symbol").GetString()).Append('\t').Append(c.GetProperty("cookie_index").GetUInt32()).Append('\t').Append(c.GetProperty("notification_owner").GetString()).Append('\t').Append(c.GetProperty("close").GetString()).Append('\t').Append(c.GetProperty("drain").GetString()).Append('\n');
        foreach (var o in model.Operations) metadata.Append("operation\t").Append(o.Name).Append('\t').Append(o.Owner).Append('\t').Append(o.Create).Append('\t').Append(o.Start).Append('\t').Append(o.RequestCancel).Append('\t').Append(o.TakeResult).Append('\t').Append(o.TryRetire).Append('\t').Append(o.Release).Append('\t').Append(o.InputEnd).Append('\n');
        return (text, metadata.ToString());
    }

    private static readonly HashSet<string> FrameworkNames = new("System IDisposable IAsyncDisposable ValueTask SafeHandle InvalidOperationException ArgumentNullException Exception Func StructLayout StructLayoutAttribute LayoutKind LibraryImport LibraryImportAttribute UnmanagedCallConv UnmanagedCallConvAttribute UnmanagedCallersOnly UnmanagedCallersOnlyAttribute CallConvCdecl".Split(' '), StringComparer.Ordinal);
    private static string OwnerParameter(BindingParameter parameter) => "Owner_" + parameter.Owner + (parameter.Nullable ? "? " : " ") + Id(parameter.Name);

    private static string Type(string type, BindingDescription model)
    {
        var parts = type.Split(':');
        if (model.Owners.Any(o => o.Kind == parts[^1])) return parts.Length == 2 ? "nint" : "nint*";
        var scalar = parts[^1] switch
        {
            "void" => "void",
            "u8" => "byte",
            "i8" => "sbyte",
            "u16" => "ushort",
            "i16" => "short",
            "u32" => "uint",
            "i32" => "int",
            "u64" => "ulong",
            "i64" => "long",
            "usize" => "nuint",
            "f32" => "float",
            "f64" => "double",
            _ => Id(parts[^1])
        };
        return scalar + new string('*', parts.Length - 1);
    }

    private static string Id(string value) => "@" + value;
    private static string LocalPrefix(BindingExport export)
    {
        var prefix = "__nw_";
        while (export.Parameters.Any(p => p.Name.StartsWith(prefix, StringComparison.Ordinal))) prefix += "_";
        return prefix;
    }
    private static void Docs(StringBuilder output, BindingExport export, string prefix)
    {
        output.Append(prefix).Append("/// <summary>Calls the exact ").Append(export.Symbol).Append(" native boundary.</summary>\n");
        foreach (var p in export.Parameters)
            output.Append(prefix).Append("/// <param name=\"").Append(p.Name).Append("\">").Append(SecurityElement.Escape(p.Type + "; " + p.Direction + "; nullable: " + p.Nullable + "; borrow ends: " + p.BorrowEnd + "; owner: " + (p.Owner.Length == 0 ? "none" : p.Owner) + "; maximum bytes: " + p.MaximumBytes + ".")).Append("</param>\n");
        if (export.ReturnType != "void") output.Append(prefix).Append("/// <returns>Exact native status; failure does not transfer an owner.</returns>\n");
        output.Append(prefix).Append("/// <remarks>").Append(export.ThreadProfile).Append("; ").Append(export.Reentrancy).Append(". One FFI call; no runtime binder or generated marshaller. Owner call leases use the A03 gate and always release in finally.</remarks>\n");
    }
    private static void Fail(string code, string message) => throw new BindingValidationException(code, new("emitter", "$", 1, 1), message);
}
